package example

import groovy.sql.Sql
import org.grails.orm.hibernate.HibernateDatastore
import spock.lang.Specification

/**
 * A table created with the GORM default discriminator column "class" must validate
 * against the same domain classes with dbCreate: 'validate'.
 */
class ValidateExistingTableSpec extends Specification {

    HibernateDatastore datastore

    void setup() {
        Sql sql = H2.sql('existing')
        try {
            sql.execute '''
                create table vehicle (
                    id bigint generated by default as identity primary key,
                    version bigint not null,
                    name varchar(255),
                    "CLASS" varchar(255) not null
                )'''
            sql.execute '''insert into vehicle (version, name, "CLASS") values
                (0, 'car', 'example.Car'), (0, 'sedan', 'example.Sedan')'''
        } finally {
            sql.close()
        }
    }

    void cleanup() {
        datastore?.close()
        Sql sql = H2.sql('existing')
        try {
            sql.execute 'drop table if exists vehicle'
        } finally {
            sql.close()
        }
    }

    void "an existing table with a class discriminator column validates and maps its rows"() {
        when:
        datastore = H2.datastore('existing', 'validate', Vehicle, Car, SportsCar, Sedan)

        then:
        noExceptionThrown()
        Vehicle.withTransaction { Vehicle.list(sort: 'id')*.getClass() } == [Car, Sedan]
    }
}
